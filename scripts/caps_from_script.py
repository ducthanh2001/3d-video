"""voice/<ep>/script.txt + sentences.json + words.json -> a TypeScript captions table (the script's own words, so Whisper's
mis-hearings never reach the screen; times from Whisper inside each sentence, first word from the real speech onset).
usage: .venv\Scripts\python.exe scripts\caps_from_script.py ep005 src/episodes/ep005-einstein-failed-math/captions.ts"""
import json
import pathlib
import re
import sys

import numpy as np
import soundfile as sf

EP, OUT = sys.argv[1], pathlib.Path(sys.argv[2])
VD = pathlib.Path(__file__).resolve().parent.parent / "voice" / EP
lines = [l.strip() for l in (VD / "script.txt").read_text(encoding="utf-8").splitlines() if l.strip()]
sents = json.loads((VD / "sentences.json").read_text(encoding="utf-8"))
words = json.loads((VD / "words.json").read_text(encoding="utf-8"))
x, sr = sf.read(VD / "voice.wav", dtype="float32")
env = np.convolve(np.abs(x), np.ones(120) / 120, "same")
SUBS = [("three hundred thousand", "300 thousand"), ("one hundred twenty", "120"), ("two point six million", "2.6 million"), ("Three hundred", "300"), ("three hundred", "300"), ("Eighteen ninety-five", "1895"), ("Nineteen oh five", "1905"), ("E T H", "ETH"), ("twelve", "12"), ("fourteen", "14"), ("Sixteen", "16"), ("Real...", "Real…"), ("Verdict:", "Verdict:")]
out = []
for i, (line, s) in enumerate(zip(lines, sents)):
    t = line
    for a, b in SUBS: t = t.replace(a, b)
    toks = t.split()
    i0 = int(s["start"] * sr)
    onset = float(np.argmax(env[i0:i0 + sr] > 0.004)) / sr + s["start"]
    nxt = sents[i + 1]["start"] - 0.05 if i + 1 < len(sents) else 1e9
    win = [w for w in words if s["start"] - 0.1 <= w["s"] < nxt]
    if len(win) == len(toks):
        ts = [onset] + [max(onset + 0.05 * k, w["s"]) for k, w in enumerate(win[1:], 1)]
    else:
        ch = np.array([len(re.sub(r"\W", "", k)) + 2 for k in toks], float)
        cum = np.concatenate([[0], np.cumsum(ch)]) / ch.sum()
        ts = [onset + (s["end"] - onset) * c for c in cum[:-1]]
        print(f"line {i + 1}: {len(win)} whisper words vs {len(toks)} -> proportional")
    for k, (tok, a) in enumerate(zip(toks, ts)):
        b = ts[k + 1] if k + 1 < len(ts) else s["end"]
        out.append({"w": tok, "s": round(a, 3), "e": round(max(a + 0.08, b - 0.02), 3)})
OUT.write_text("// generated by scripts/caps_from_script.py from voice/" + EP + ": the script's words with their times (seconds)\nexport const CAPTION_WORDS: { w: string; s: number; e: number }[] = " + json.dumps(out, indent=1) + ";\n", encoding="utf-8")
print(len(out), "caption words ->", OUT)
