"""voice/<ep>/voice.wav -> a per-frame mouth-opening table (0..1) from the real loudness of the speech, so the narrator's mouth follows
the syllables of the voice instead of a fixed flap. A 50 ms RMS window at 30 fps, noise gate, normalised to the 90th percentile, 3-tap smooth.
usage: .venv\Scripts\python.exe scripts\mouth_from_voice.py ep007 src/episodes/ep007-thermopylae/mouth.ts [frames]"""
import pathlib
import sys

import numpy as np
import soundfile as sf

EP, OUT = sys.argv[1], pathlib.Path(sys.argv[2])
FR = int(sys.argv[3]) if len(sys.argv) > 3 else 0
x, sr = sf.read(pathlib.Path(__file__).resolve().parent.parent / "voice" / EP / "voice.wav", dtype="float32")
n = FR or int(len(x) / sr * 30) + 1
r = np.zeros(n)
for f in range(n):
    c = int((f + 0.5) / 30 * sr); a = x[max(0, c - int(0.025 * sr)):c + int(0.025 * sr)]
    r[f] = np.sqrt(np.mean(a ** 2)) if len(a) else 0
gate = 0.012
hi = np.percentile(r[r > gate], 90) if (r > gate).any() else 1
m = np.clip((r - gate) / (hi - gate), 0, 1) ** 0.8
m = np.clip((m - 0.12) / 0.88, 0, 1)  # the mouth closes between syllables
m = np.convolve(np.pad(m, 1, mode="edge"), [0.25, 0.5, 0.25], "valid")
OUT.write_text("// generated by scripts/mouth_from_voice.py from voice/" + EP + "/voice.wav: mouth opening 0..1 per frame (30 fps)\nexport const MOUTH: number[] = [" + ",".join(f"{v:.2f}" for v in m) + "];\n", encoding="utf-8")
print(n, "frames ->", OUT)
